#!/usr/bin/env python3
"""Split the generated corpus into one assembly module per card."""

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# Include each effect's description, program header, instructions and terminator.
BLOCK = re.compile(
    r'^; (?P<name>[^\n]+): effect (?P<effect>\d+) [^\n]*\n'
    r'\.program (?P<card>\d+)_(?P=effect)\n'
    r'.*?^\.end[^\S\n]*(?:\n|$)',
    re.MULTILINE | re.DOTALL,
)


def split(source: str) -> dict[str, str]:
    cards: dict[str, list[str]] = {}
    names: dict[str, str] = {}
    seen: set[tuple[str, str]] = set()
    matches = list(BLOCK.finditer(source))
    if not matches:
        raise ValueError('No card programs found')
    end = 0
    for match in matches:
        # Reject unrecognized content rather than silently dropping instructions.
        gap = source[end:match.start()]
        if any(line.strip() and not line.lstrip().startswith(';') for line in gap.splitlines()):
            raise ValueError('Unexpected content outside a card program')
        card, name, effect = match.group('card', 'name', 'effect')
        if (card, effect) in seen:
            raise ValueError(f'Duplicate program {card}_{effect}')
        if card in names and names[card] != name:
            raise ValueError(f'Conflicting names for card {card}')
        block = match.group()
        if len(re.findall(r'^\.program\b', block, re.MULTILINE)) != 1:
            raise ValueError(f'Missing terminator in program {card}_{effect}')
        seen.add((card, effect))
        names[card] = name
        cards.setdefault(card, []).append(block)
        end = match.end()
    if source[end:].strip():
        raise ValueError('Unexpected trailing content')
    outputs = {}
    for card, blocks in cards.items():
        slug = re.sub(r'[^a-z0-9]+', '_', names[card].lower()).strip('_')
        filename = f'{card}_{slug or "card"}.lasm'
        header = (
            '; Generated by tools/split_effects.py from data/effects.lasm.\n'
            '; Shared numeric state ABI: ../effects.bindings.json.\n'
            '; Each .program retains its original PCs, registers and labels.\n\n'
        )
        outputs[filename] = header + '\n'.join(blocks)
    return outputs


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify files without writing them')
    args = parser.parse_args()
    source = (ROOT / 'data/effects.lasm').read_text(encoding='utf-8')
    outputs = split(source)
    destination = ROOT / 'data/cards'
    existing = set(destination.glob('*.lasm'))
    expected = {destination / name for name in outputs}
    stale = existing - expected
    if stale:
        raise SystemExit('Unexpected card files; review before removing: ' + ', '.join(str(p) for p in sorted(stale)))
    if not args.check:
        destination.mkdir(parents=True, exist_ok=True)
    for name, content in outputs.items():
        path = destination / name
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                raise SystemExit(f'{path} is stale; run tools/split_effects.py')
        else:
            path.write_text(content, encoding='utf-8')
    programs = sum(len(re.findall(r'^\.program\b', text, re.MULTILINE)) for text in outputs.values())
    print(f'{len(outputs)} card files, {programs} programs' + (' verified' if args.check else ' written'))


if __name__ == '__main__':
    main()
